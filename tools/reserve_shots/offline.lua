-- Haven Reserve offline: the warden keeps the Pokémon in the save, it
-- roams with the day's strays, and the notice board lists who's there.
--   python3 tools/reserve_shots/run.py tools/reserve_shots/offline.lua OUT 30000 1
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY

D.run(function()
    D.boot()
    D.summer()
    D.showcase({ level = 22, badges = 2, party = { "GROVYLE", "WINGULL", "SKITTY" } })
    D.scene(12, MAPS.MAP_VERDANTURF_TOWN, 14, 10)
    D.talk(K.UP, "off-gate-guard", 4)
    D.wait(50)
    D.press(K.A, 10)
    D.wait(300)
    D.waitFor("the reserve", 1200, D.inOverworld)
    D.wait(150)
    D.scene(12, MAPS.MAP_HAVEN_RESERVE, 13, 25)
    D.talk(K.UP, "off-warden", 4)
    D.wait(40)
    D.press(K.A, 90)
    D.press(K.DOWN, 20)
    D.press(K.DOWN, 20)
    D.press(K.A, 150)
    D.press(K.A, 120)
    D.press(K.A, 10) -- YES
    D.wait(120)
    D.shot("off-warden-offline")
    D.press(K.A, 60)
    D.shot("off-warden-left")
    D.press(K.A, 40)
    D.wait(60)
    D.scene(12, MAPS.MAP_HAVEN_RESERVE, 21, 24)
    D.talk(K.UP, "off-board-intro")
    D.wait(120)
    D.shot("off-board")
    D.press(K.B, 60)
    -- The Skitty came after the day's three strays: object 4 (starts at 9,12).
    D.scene(12, MAPS.MAP_HAVEN_RESERVE, 9, 14)
    D.approach(4)
    D.wait(130)
    D.shot("off-mine")
    D.press(K.A, 60)
    D.press(K.B, 60)
    -- The lodge: the nurse heals, the head guard explains.
    D.scene(12, MAPS.MAP_HAVEN_RESERVE_LODGE, 7, 5)
    D.talk(K.UP, "off-lodge-nurse")
    D.press(K.A, 300)
    D.press(K.A, 60)
    D.scene(12, MAPS.MAP_HAVEN_RESERVE_LODGE, 3, 4)
    D.talk(K.LEFT, "off-lodge-head-guard", 3)
end)
