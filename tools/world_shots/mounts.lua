-- Mounts: open the R menu, ride Rapidash, ride around, get off.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY

D.run(function()
    D.boot()
    D.wait(60)
    D.scene(13, MAPS.MAP_ROUTE103, 10, 12, { give = "RAPIDASH", level = 40 })
    D.press(K.R, 40)
    D.shot("r-menu")
    D.press(K.A, 120)
    D.shot("riding")
    D.hold(K.LEFT, 24)
    D.shot("riding-left")
    D.hold(K.DOWN, 10)
    D.wait(20)
    D.shot("riding-down")
    D.hold(K.UP, 16)
    D.wait(20)
    D.shot("riding-up")
    D.scene(13, MAPS.MAP_ROUTE111, 21, 100, { give = "ARCANINE", level = 50, lead = true })
    D.press(K.R, 40)
    D.press(K.A, 120)
    D.hold(K.UP, 30)
    D.wait(20)
    D.shot("arcanine-desert")
end)
