dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
D.run(function()
    D.boot()
    D.waitFor("the server", 600, D.online)
    D.wait(120)
    local before = D.answers()
    D.community(5, "menu")
    D.waitAnswer(before)
    D.wait(30)
    D.shot("rooms")
    before = D.answers()
    D.press(K.A, 10)
    D.waitAnswer(before)
    D.wait(40)
    D.shot("room")
    if INSTANCE == 1 then
        D.press(K.A, 120)
        D.shot("ec1")
        D.press(K.A, 60) D.shot("ec2")
        D.press(K.A, 60) D.shot("ec3")
        D.press(K.A, 60) D.shot("ec4")
        D.press(K.START, 60) D.shot("ec5")
        D.press(K.A, 60) D.shot("ec6")
        D.press(K.A, 120) D.shot("ec7")
        D.wait(120) D.shot("after")
    else
        D.wait(1200)
        D.shot("p2-sees")
    end
end)
