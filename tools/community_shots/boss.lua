dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local P1 = INSTANCE == 1
D.run(function()
    D.boot()
    D.waitFor("the server", 600, D.online)
    D.showcase({ level = 90, party = P1 and { "ELECTIVIRE", "SCEPTILE", "GARCHOMP" } or { "LUDICOLO", "MAGNEZONE" }, badges = 8 })
    D.scene(13, MAPS.MAP_OLDALE_TOWN, P1 and 6 or 8, 12)
    if not P1 then D.wait(1500) end
    local before = D.answers()
    D.community(2, "menu")
    D.waitAnswer(before)
    D.wait(40)
    D.shot("status")
    D.press(K.A, 10)
    D.waitFor("the battle", 1200, D.inBattle)
    D.wait(400)
    D.shot("battle")
    local shot = false
    D.waitFor("the end of the battle", 20000, D.inOverworld, function(i)
        local cycle = { K.A, K.A, K.A, K.A, K.DOWN, K.A, K.B }
        if i % 30 == 0 then D.press(cycle[(i // 30) % #cycle + 1], 0) end
        if not shot and i == 900 then D.shot("battle-hit"); shot = true end
    end)
    D.wait(60)
    D.shot("damage")
    D.press(K.A, 30)
    D.press(K.A, 60)
    D.wait(300)
    D.shot("later")
    D.press(K.A, 60) D.shot("later2")
    D.press(K.A, 60)
    D.wait(120)
    before = D.answers()
    D.community(2)
    D.waitAnswer(before)
    D.wait(40)
    D.shot("reward-status")
    D.press(K.A, 90) D.shot("reward1")
    D.press(K.A, 90) D.shot("reward2")
    D.press(K.A, 120) D.shot("reward3")
    D.press(K.A, 120) D.shot("reward4")
    D.press(K.A, 120) D.shot("reward5")
end)
