dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local P1 = INSTANCE == 1
local function open(name)
    local before = D.answers()
    D.community(1)
    D.waitAnswer(before)
    D.wait(50)
    D.shot(name)
end
D.run(function()
    D.boot()
    D.waitFor("the server", 600, D.online)
    D.showcase({ level = 40, party = P1 and { "SCEPTILE", "SWELLOW" } or { "DITTO", "ALTARIA" } })
    D.scene(13, MAPS.MAP_ROUTE117, P1 and 47 or 49, 10)
    if not P1 then D.wait(900) end
    open("status")
    D.press(K.A, 50) D.shot("status2")
    D.press(K.A, 40) D.press(K.A, 40) D.wait(30) D.shot("pairq")
    local before = D.answers()
    D.press(K.A, 10)
    D.waitAnswer(before) D.wait(40) D.shot("partners")
    D.press(K.A, 60) D.shot("whichmon")
    D.press(K.A, 120) D.shot("party")
    before = D.answers()
    D.waitFor("the request", 900, function() return D.answers() ~= before end, function(i)
        if i % 60 == 30 then D.press(K.A, 0) end
    end) D.wait(80) D.shot("left")
    D.press(K.A, 40)
    D.wait(P1 and 3000 or 600)
    D.shot("before-later")
    open("status-later")
    D.press(K.A, 50) D.shot("status-later2")
    D.press(K.A, 60) D.shot("egg1")
    D.press(K.A, 120) D.shot("egg2")
    D.press(K.A, 120) D.shot("egg3")
    D.press(K.START, 40) D.press(K.A, 120) D.shot("party-after")
end)
