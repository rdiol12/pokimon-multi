def main():
    src = Image.open(SRC)
    icons = len(OLD) + len(NEW)
    out = Image.new("P", (icons * 2 * 16, 16), 0)
    out.putpalette(src.getpalette())
    blank = src.crop((0, 0, 16, 16)).load()  # frame 0: take the bubble from it
    for i, frame in enumerate(OLD):
        for f in range(2):
            out.paste(src.crop(((frame + f) * 16, 0, (frame + f + 1) * 16, 16)), ((i * 2 + f) * 16, 0))
    px = out.load()
    for n, (name, frames) in enumerate(NEW.items()):
        i = len(OLD) + n
        for f, rows in enumerate(frames):
            ox = (i * 2 + f) * 16
            assert len(rows) == 11 and all(len(r) == 13 for r in rows), name
            for y in range(16):
                for x in range(16):
                    v = blank[x, y]
                    corner = x in (1, 13) and y in (1, 11)  # the bubble's rounded corners
                    if 1 <= x <= 13 and 1 <= y <= 11 and not corner:
                        c = rows[y - 1][x - 1]
                        v = 0xF if c == "." else int(c, 16)
                    px[ox + x, y] = v
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    out.save(OUT)

    # The wheel's cursor: a 32x32 ring, orange with a dark rim, around the picked icon.
    ring = Image.new("P", (32, 32), 0)
    ring.putpalette(src.getpalette())
    rp = ring.load()
    for y in range(32):
        for x in range(32):
            d = ((x - 15.5) ** 2 + (y - 15.5) ** 2) ** 0.5
            if 12.5 <= d < 14.5:
                rp[x, y] = 8
            elif 11.5 <= d < 12.5 or 14.5 <= d < 15.5:
                rp[x, y] = 3
    ring.save(CURSOR)


if __name__ == "__main__":
    main()
