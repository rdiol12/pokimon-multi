-- Whisperstem Valley: the teahouse, before and after the three Pancham are home.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local TEA = MAPS.MAP_WHISPERSTEM_VALLEY_TEAHOUSE

D.run(function()
    D.boot()
    D.wait(60)
    D.season(1)
    D.scene(12, TEA, 3, 4)
    D.wait(150)
    D.shot("01-teahouse")
    D.talk(K.UP, "02-master-asks", 3)
    D.press(K.B, 30)
    D.flag("FLAG_BAMBOO_PANCHAM_1", true)
    D.flag("FLAG_BAMBOO_PANCHAM_2", true)
    D.flag("FLAG_BAMBOO_PANCHAM_3", true)
    D.scene(12, TEA, 3, 4)
    D.wait(150)
    D.shot("03-all-home")
    D.talk(K.UP, "04-master-thanks", 3)
    D.wait(120)
    D.shot("05-got-pancham")
    D.press(K.A, 60)
    D.wait(200)
    D.shot("06-master-after")
    D.press(K.A, 40)
    D.result("ok")
end)
