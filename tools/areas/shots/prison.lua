-- Ironmoor Prison: the boatman on Route 109 (badge check), the landing,
-- the rusted gate, the graveyard and the breach, a searchlight catching
-- you, cutting the power, knocking the gate's bolt loose, the cell block,
-- the warden's key, the iron gate, the cell console, freeing a spirit and
-- Spiritomb rising from the Odd Keystone.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local I = MAPS.MAP_IRONMOOR_ISLE
local C = MAPS.MAP_IRONMOOR_PRISON
local S = MAPS.MAP_IRONMOOR_PRISON_SOLITARY

local function close(n)
    for _ = 1, n do D.press(K.A, 30) end
    D.press(K.B, 30)
end

local function at(map, x, y)
    D.scene(12, map, x, y)
    D.wait(300)
end

local function walk(dir, n)
    for _ = 1, n do D.hold(dir, 16) end
    D.wait(30)
end

D.run(function()
    D.boot()
    D.wait(60)
    D.season(1)
    D.scene(12, MAPS.MAP_ROUTE109, 17, 22, { give = "LUCARIO", level = 35, lead = true })
    D.wait(300)
    D.talk(K.UP, "01-boatman-needs-badges", 3)
    D.press(K.B, 60)
    D.wait(60)
    D.flag("FLAG_BADGE04_GET", true)
    D.talk(K.UP, "02-boatman", 2)
    for _ = 1, 4 do D.press(K.A, 60) end
    D.wait(400)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(200)
    D.shot("03-landing")
    at(I, 22, 24)
    D.talk(K.UP, "04-gate-rusted", 1)
    close(1)
    at(I, 9, 27)
    D.shot("05-graveyard")
    at(I, 8, 24)
    walk(K.UP, 3)
    D.shot("06-through-the-breach")
    at(I, 12, 18)
    D.hold(K.UP, 16)
    D.wait(120)
    D.shot("07-spotted")
    D.press(K.A, 60)
    D.wait(30)
    D.shot("08-ghost-guards")
    close(2)
    D.wait(200)
    D.shot("09-back-at-the-breach")
    at(I, 35, 21)
    D.talk(K.UP, "10-generator", 2)
    D.wait(150)
    D.shot("11-lights-out")
    close(2)
    at(I, 16, 19)
    walk(K.UP, 3)
    D.shot("12-crossing-the-yard")
    at(I, 22, 21)
    D.talk(K.DOWN, "13-gate-bolt", 3)
    D.wait(200)
    D.shot("14-gate-up")
    close(1)
    at(I, 22, 8)
    D.shot("15-cell-block")
    walk(K.UP, 3)
    D.wait(300)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(100)
    D.shot("16-inside")
    at(C, 14, 11)
    D.talk(K.UP, "17-iron-gate-locked", 2)
    close(1)
    at(C, 23, 19)
    D.talk(K.UP, "18-warden-desk", 4)
    D.wait(100)
    D.shot("19-warden-key")
    close(2)
    at(C, 14, 11)
    D.talk(K.UP, "20-iron-gate", 1)
    D.wait(120)
    D.shot("21-iron-gate-opens")
    close(1)
    at(C, 2, 5)
    D.talk(K.UP, "22-cell-console", 2)
    D.wait(150)
    D.shot("23-cells-open")
    close(1)
    at(C, 14, 6)
    D.shot("24-cell-hall")
    at(C, 10, 2)
    D.talk(K.UP, "25-bound-spirit", 3)
    D.wait(120)
    D.shot("26-spirit-drifts")
    close(1)
    D.flag("FLAG_IRONMOOR_SPIRIT_2", true)
    D.flag("FLAG_IRONMOOR_SPIRIT_3", true)
    D.flag("FLAG_IRONMOOR_SPIRIT_4", true)
    at(S, 21, 11)
    D.shot("27-odd-keystone")
    D.talk(K.UP, "28-keystone", 2)
    D.wait(200)
    D.shot("29-keystone-cracks")
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(300)
    D.shot("30-spiritomb-battle")
    D.result("ok")
end)
