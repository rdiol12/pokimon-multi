-- Gullwing Point: the boatman in Dewford, the cape, the keeper, the mirror
-- puzzle and the beam, the gangplank, the pirate deck, the captain and the hold.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local GP = MAPS.MAP_GULLWING_POINT

local function say(dir, name, pages)
    D.talk(dir, name, pages)
    D.wait(30)
end

local function close(n)
    for _ = 1, n do D.press(K.A, 30) end
    D.press(K.B, 30)
end

local function turn(x, y, dir, name)
    D.scene(12, GP, x, y)
    D.wait(30)
    D.talk(dir, name, 1)
    D.press(K.A, 90)
end

D.run(function()
    D.boot()
    D.wait(60)
    D.season(1)
    D.scene(12, MAPS.MAP_DEWFORD_TOWN, 5, 12, { give = "GYARADOS", level = 60, lead = true })
    D.wait(240)
    say(K.RIGHT, "01-boatman", 2)
    D.press(K.A, 40)
    D.press(K.A, 40)
    D.wait(200)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(150)
    D.shot("02-arrive")
    D.scene(12, GP, 12, 17); D.wait(90); D.shot("03-village")
    D.scene(12, GP, 42, 12); say(K.UP, "04-keeper", 4); close(2)
    D.scene(12, GP, 38, 14); say(K.UP, "05-plaque", 2); close(1)
    D.scene(12, GP, 37, 19); D.wait(60); D.shot("06-mirrors")
    turn(41, 16, K.UP, "07-mirror-1")
    turn(33, 16, K.UP, "08-mirror-2")
    turn(33, 23, K.UP, "09-mirror-3")
    D.shot("10-three-turned")
    turn(37, 23, K.UP, "11-mirror-4")
    D.wait(120)
    D.shot("12-beam")
    D.press(K.A, 120)
    D.shot("13-gangplank")
    close(2)
    D.scene(12, GP, 36, 20); D.wait(60); D.shot("14-beam-path")
    D.scene(12, GP, 26, 35); D.wait(60); D.shot("15-pier")
    D.hold(K.RIGHT, 40)
    D.wait(150)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(60)
    D.shot("16-deck")
    D.scene(12, MAPS.MAP_GULLWING_POINT_PIRATE_HOLD, 8, 4); say(K.LEFT, "17-guard-says-no", 1)
    D.press(K.A, 60)
    D.wait(200)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(60)
    D.shot("18-thrown-out")
    D.flag("FLAG_GULL_CAPTAIN_BEATEN", true)
    D.scene(12, MAPS.MAP_GULLWING_POINT_PIRATE_HOLD, 15, 3); D.wait(90); D.shot("19-hold")
    D.scene(12, MAPS.MAP_GULLWING_POINT_PIRATE_HOLD, 8, 4); say(K.LEFT, "20-guard-ok", 1); close(1)
    D.scene(12, MAPS.MAP_GULLWING_POINT_PIRATE_HOLD, 1, 10); say(K.UP, "21-big-nugget", 1); close(2)
    D.scene(12, GP, 42, 12); say(K.UP, "22-keeper-thanks", 1); close(1)
    D.result("ok")
end)
