-- Sunfair Carnival: the guide in Slateport, the fairground by day and night,
-- the four game hosts, the stalls, and the Ringmaster's runaway Spinda.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local SC = MAPS.MAP_SUNFAIR_CARNIVAL

local function say(dir, name, pages)
    D.talk(dir, name, pages)
    D.wait(30)
end

local function close(n)
    for _ = 1, n do D.press(K.A, 30) end
    D.press(K.B, 30)
end

D.run(function()
    D.boot()
    D.wait(60)
    D.season(1)
    D.scene(12, MAPS.MAP_SLATEPORT_CITY, 9, 23)
    D.wait(240)
    say(K.LEFT, "01-guide", 2)
    D.press(K.A, 40)
    D.press(K.A, 40)
    D.wait(200)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(150)
    D.shot("02-arrive")
    D.scene(12, SC, 29, 38); D.wait(90); D.shot("03-arch")
    D.scene(12, SC, 29, 16); D.wait(90); D.shot("04-ferris-wheel")
    D.scene(12, SC, 29, 13); say(K.UP, "05-ferris-host", 1); close(2)
    D.scene(12, SC, 9, 14); say(K.UP, "06-bowling-host", 1); close(2)
    D.scene(12, SC, 39, 27); say(K.UP, "07-golf-host", 1); close(2)
    D.scene(12, SC, 12, 27); say(K.UP, "08-soccer-host", 1); close(2)
    D.scene(12, SC, 34, 20); say(K.UP, "09-drinks-stall", 1)
    D.press(K.A, 60)
    D.shot("10-drinks-menu")
    D.press(K.B, 40); D.press(K.B, 40); close(1)
    D.scene(12, SC, 25, 20); say(K.UP, "11-ring-toss", 2)
    D.press(K.A, 60)
    D.shot("12-ring-toss-throw")
    close(3)
    D.scene(12, SC, 50, 20); say(K.UP, "13-fortune-teller", 2)
    close(2)
    D.scene(12, SC, 11, 16); say(K.UP, "14-ringmaster", 3)
    close(5)
    D.scene(12, SC, 50, 8); D.wait(60); D.shot("15-bowling-ground")
    D.scene(12, SC, 52, 7); D.wait(30)
    say(K.UP, "16-spinda", 1)
    D.press(K.A, 120)
    D.shot("17-spinda-back")
    close(1)
    D.scene(12, SC, 11, 16); say(K.UP, "18-ringmaster-thanks", 2)
    D.press(K.A, 300)
    D.shot("19-mime-jr-egg")
    close(3)
    D.scene(12, SC, 12, 18); D.wait(60); D.shot("20-spinda-home")
    D.scene(22, SC, 29, 16); D.wait(90); D.shot("21-night")
    D.result("ok")
end)
