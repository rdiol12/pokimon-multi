-- Prism Caverns: the last crystal, the seal breaking, Diancie, Dr. Mica's
-- Glimmet and the white pad to the geode grotto.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local P = MAPS.MAP_PRISM_CAVERNS
local B = MAPS.MAP_PRISM_CAVERNS_DEPTHS

D.run(function()
    D.boot()
    D.wait(60)
    D.season(1)
    D.flag("FLAG_PRISM_RUBY", true)
    D.flag("FLAG_PRISM_SAPPHIRE", true)
    D.flag("FLAG_PRISM_EMERALD", true)
    D.scene(12, B, 43, 20, { give = "LUCARIO", level = 45, lead = true })
    D.wait(300)
    D.talk(K.UP, "01-touch-topaz", 3)
    D.wait(150)
    D.shot("02-topaz-lit")
    D.press(K.A, 30)
    D.wait(150)
    D.shot("03-gold-plates")
    D.press(K.A, 30)
    D.wait(90)
    D.shot("04-all-four")
    D.press(K.A, 30)
    D.wait(20)
    D.shot("05-rumble")
    D.wait(120)
    D.shot("06-seal-shatters")
    D.press(K.A, 30)
    D.press(K.B, 30)
    D.scene(12, B, 24, 26)
    D.wait(300)
    D.shot("07-seal-open")
    D.scene(12, P, 24, 35)
    D.wait(300)
    D.talk(K.UP, "10-mica-thanks", 3)
    D.wait(150)
    D.shot("11-got-glimmet")
    for _ = 1, 4 do D.press(K.A, 50) end
    D.wait(60)
    D.shot("12-mica-white-plate")
    D.press(K.A, 40)
    D.press(K.B, 40)
    D.scene(12, P, 28, 31)
    D.wait(300)
    D.shot("13-white-pad")
    D.hold(K.UP, 16)
    D.wait(300)
    D.shot("14-geode-grotto")
    D.scene(12, B, 24, 9)
    D.wait(300)
    D.talk(K.UP, "15-diancie", 2)
    D.press(K.A, 60)
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(300)
    D.shot("16-diancie-battle")
    D.result("ok")
end)
