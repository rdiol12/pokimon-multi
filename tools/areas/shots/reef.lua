-- Coralline Reef and Abyssia: the diver in Pacifidlog, the reef, the clam,
-- the shipwreck and its Dhelmise, the sunken city, Marina, the four lamps,
-- the temple opening and the Relicanth inside.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local RF, AB = MAPS.MAP_CORALLINE_REEF, MAPS.MAP_ABYSSIA

local function say(dir, name, pages)
    D.talk(dir, name, pages)
    D.wait(30)
end

local function close(n)
    for _ = 1, n do D.press(K.A, 30) end
    D.press(K.B, 30)
end

local function battle(name)
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(400)
    D.shot(name)
    -- the Lv80 lead wins with its first move
    D.waitFor("the overworld", 4000, D.inOverworld, function(i) if i % 20 == 0 then D.press(K.A, 0) end end)
    D.wait(60)
end

D.run(function()
    D.boot()
    D.wait(60)
    D.season(1)
    D.flag("FLAG_BADGE07_GET", true)
    D.scene(12, MAPS.MAP_PACIFIDLOG_TOWN, 8, 19, { give = "GYARADOS", level = 80, lead = true })
    D.wait(240)
    say(K.UP, "01-diver", 2)
    D.press(K.A, 40)
    D.press(K.A, 40)
    D.wait(200)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(150)
    D.shot("02-arrive")
    D.scene(12, RF, 28, 26); D.wait(90); D.shot("03-coral-garden")
    D.scene(12, RF, 46, 10); say(K.UP, "04-giant-clam", 1); close(3)
    D.scene(12, RF, 9, 13); D.wait(90); D.shot("05-wreck")
    D.scene(12, RF, 7, 12); D.wait(60)
    D.hold(K.UP, 40)
    D.wait(150)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(60)
    D.shot("06-inside-the-wreck")
    D.scene(12, MAPS.MAP_CORALLINE_REEF_WRECK, 9, 2); say(K.UP, "07-captains-log", 2); close(2)
    D.scene(12, MAPS.MAP_CORALLINE_REEF_WRECK, 16, 3); say(K.RIGHT, "08-dhelmise", 1)
    battle("09-dhelmise-battle")
    D.scene(12, AB, 28, 40); D.wait(90); D.shot("10-abyssia")
    D.scene(12, AB, 28, 20); D.wait(90); D.shot("11-city-centre")
    D.scene(12, AB, 28, 33); say(K.UP, "12-marina", 7); close(1)
    D.scene(12, AB, 18, 17); say(K.UP, "13-lamp", 1)
    D.press(K.A, 120)
    D.shot("14-lamp-glows")
    close(1)
    D.flag("FLAG_ABYSS_LAMP_2", true)
    D.flag("FLAG_ABYSS_LAMP_3", true)
    D.scene(12, AB, 37, 33); say(K.UP, "15-last-lamp", 1)
    D.press(K.A, 120)
    D.press(K.A, 60)
    D.wait(120)
    D.shot("16-temple-opens")
    close(2)
    D.scene(12, AB, 28, 11); D.wait(240); D.shot("17-temple-open")
    D.scene(12, AB, 28, 33); say(K.UP, "18-marina-thanks", 2); close(6)
    D.scene(12, AB, 28, 10); D.wait(60)
    D.hold(K.UP, 40)
    D.wait(150)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(60)
    D.shot("19-temple-inside")
    D.scene(12, MAPS.MAP_ABYSSIA_TEMPLE, 10, 6); say(K.UP, "20-relicanth", 1)
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(400)
    D.shot("21-relicanth-battle")
    D.result("ok")
end)
