-- Nimbus Isles: bringing the chimes back, the tower ringing, the summit
-- wind and Tornadus at the shrine.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local C, I = MAPS.MAP_NIMBUS_CITY, MAPS.MAP_NIMBUS_ISLE

D.run(function()
    D.boot()
    D.wait(60)
    D.season(1)
    D.flag("FLAG_NIMBUS_CHIME_1", true)
    D.flag("FLAG_NIMBUS_CHIME_2", true)
    D.flag("FLAG_NIMBUS_CHIME_3", true)
    D.scene(12, C, 19, 10, { give = "ALTARIA", level = 55, lead = true })
    D.wait(150)
    D.talk(K.UP, "01-keeper-thanks", 2)
    D.wait(150)
    D.shot("02-tower-sings")
    D.press(K.A, 60)
    D.press(K.A, 60)
    D.wait(120)
    D.shot("03-got-castform")
    for _ = 1, 6 do D.press(K.A, 50) end
    D.press(K.B, 40)
    D.scene(12, C, 22, 7)
    D.wait(300)
    D.shot("04-tower-ringing")
    D.scene(12, I, 41, 16)
    D.wait(300)
    D.shot("05-summit-wind")
    D.hold(K.UP, 40)
    D.wait(200)
    D.shot("06-summit")
    D.scene(12, I, 43, 7)
    D.talk(K.UP, "07-shrine", 1)
    D.press(K.A, 60)
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(300)
    D.shot("08-tornadus")
    D.result("ok")
end)
