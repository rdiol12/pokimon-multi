-- Voltspire Power Plant: the chief's reward once the power is back on.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY

D.run(function()
    D.boot()
    D.wait(60)
    D.season(1)
    D.flag("FLAG_VOLT_POWER_ON", true)
    D.scene(12, MAPS.MAP_VOLTSPIRE_PLANT, 23, 27)
    D.wait(150)
    D.shot("01-generator-room-on")
    D.talk(K.UP, "02-chief-thanks", 3)
    D.wait(150)
    D.shot("03-got-tm")
    D.press(K.A, 60)
    D.press(K.A, 60)
    D.wait(60)
    D.shot("04-chief-after")
    D.press(K.A, 40)
    D.scene(12, MAPS.MAP_VOLTSPIRE_PLANT, 19, 8)
    D.wait(120)
    D.shot("05-generator-running")
    D.result("ok")
end)
