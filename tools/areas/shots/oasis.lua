-- Mirage Oasis: the caravan master on Route 111 (badge check), the dunes,
-- a mirage melting away and the haze lifting, the oasis gate and village,
-- the elder's request, the bazaar, sinking through the quicksand to the
-- sunken court, the Spring Stone, the spring flowing again, Larvesta and
-- Landorus on the mesa.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local DU = MAPS.MAP_MIRAGE_DUNES
local O = MAPS.MAP_MIRAGE_OASIS
local C = MAPS.MAP_MIRAGE_OASIS_SUNKEN_COURT

local function close(n)
    for _ = 1, n do D.press(K.A, 30) end
    D.press(K.B, 30)
end

local function at(map, x, y)
    D.scene(12, map, x, y)
    D.wait(300)
end

local function walk(dir, n)
    for _ = 1, n do D.hold(dir, 16) end
    D.wait(30)
end

D.run(function()
    D.boot()
    D.wait(60)
    D.season(1)
    D.scene(12, MAPS.MAP_ROUTE111, 20, 106, { give = "LUCARIO", level = 60, lead = true })
    D.wait(300)
    D.talk(K.UP, "01-caravan-master-needs-badges", 3)
    close(3)
    D.wait(60)
    D.flag("FLAG_BADGE08_GET", true)
    D.talk(K.UP, "02-caravan-master", 3)
    for _ = 1, 8 do D.press(K.A, 60) end
    D.wait(400)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(300)
    D.shot("03-dunes-arrive")
    at(DU, 28, 44)
    D.shot("04-caravan-camp")
    at(DU, 27, 8)
    D.shot("05-haze-in-the-pass")
    D.flag("FLAG_MIRAGE_2", true)
    D.flag("FLAG_MIRAGE_3", true)
    at(DU, 8, 31)
    D.shot("06-a-pool-in-the-dunes")
    walk(K.UP, 2)
    D.shot("07-walking-in")
    D.hold(K.UP, 16)
    D.wait(90)
    D.shot("08-it-melts")
    D.press(K.A, 80)
    D.wait(60)
    D.shot("09-only-a-mirage")
    D.press(K.A, 80)
    D.press(K.A, 80)
    D.wait(150)
    D.shot("10-haze-lifts")
    D.press(K.A, 80)
    D.wait(60)
    D.shot("10b-gate")
    close(3)
    at(DU, 27, 7)
    D.shot("11-gate-open")
    at(DU, 27, 3)
    walk(K.UP, 4)
    D.wait(120)
    D.shot("12-the-real-oasis")
    at(O, 24, 24)
    D.shot("13-dry-pond")
    at(O, 27, 27)
    D.talk(K.UP, "14-elder", 7)
    close(1)
    at(O, 7, 32)
    D.talk(K.UP, "15-bazaar", 1)
    D.wait(120)
    D.shot("16-bazaar-goods")
    D.press(K.B, 60)
    D.press(K.B, 60)
    close(1)
    at(O, 17, 32)
    D.talk(K.UP, "17-fortune-teller", 3)
    close(1)
    at(DU, 22, 13)
    D.shot("18-three-stones")
    walk(K.UP, 2)
    D.wait(10)
    D.shot("19-sinking")
    D.wait(300)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(120)
    D.shot("20-sunken-court")
    at(C, 19, 10)
    D.talk(K.UP, "21-altar", 2)
    D.press(K.A, 60)
    D.wait(100)
    D.shot("22-spring-stone")
    close(2)
    at(C, 20, 7)
    walk(K.UP, 1)
    D.wait(300)
    D.shot("23-back-up-the-stairs")
    at(O, 25, 27)
    D.talk(K.UP, "24-well", 2)
    D.press(K.A, 60)
    D.wait(30)
    D.shot("25-stone-lowered")
    D.press(K.A, 40)
    D.wait(120)
    D.shot("26-water-rises")
    D.wait(100)
    D.shot("27-spring-flows")
    close(1)
    at(O, 24, 22)
    D.shot("28-pond-full")
    at(O, 27, 27)
    D.talk(K.UP, "29-elder-thanks", 4)
    D.wait(150)
    D.shot("30-got-larvesta")
    for _ = 1, 4 do D.press(K.A, 50) end
    D.press(K.B, 40)
    at(O, 24, 4)
    D.shot("31-landorus-on-the-mesa")
    D.talk(K.UP, "32-landorus", 2)
    D.press(K.A, 60)
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(300)
    D.shot("33-landorus-battle")
    D.result("ok")
end)
