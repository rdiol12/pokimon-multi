-- Prism Caverns: the geologist in Meteor Falls (badge check), the camp,
-- Dr. Mica's request, lighting the ruby, riding the red pad to the west
-- gallery, lighting the sapphire, the blue pad to the north hall, the
-- ladder to the Depths, the pad maze to the emerald and the topaz, the
-- seal breaking and Diancie by the heart crystal.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local P = MAPS.MAP_PRISM_CAVERNS
local B = MAPS.MAP_PRISM_CAVERNS_DEPTHS

local function close(n)
    for _ = 1, n do D.press(K.A, 30) end
    D.press(K.B, 30)
end

local function at(map, x, y)
    D.scene(12, map, x, y)
    D.wait(300)
end

local function step(dir, name)
    D.hold(dir, 16)
    D.wait(30)
    if name then D.shot(name) end
    D.wait(220)
end

D.run(function()
    D.boot()
    D.wait(60)
    D.season(1)
    D.scene(12, MAPS.MAP_METEOR_FALLS_1F_1R, 25, 18, { give = "LUCARIO", level = 45, lead = true })
    D.wait(300)
    D.talk(K.UP, "01-guide-needs-badges", 2)
    close(2)
    D.wait(60)
    D.flag("FLAG_BADGE05_GET", true)
    D.talk(K.UP, "02-guide", 2)
    for _ = 1, 6 do D.press(K.A, 60) end
    D.wait(400)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(300)
    D.shot("03-camp")
    at(P, 24, 35)
    D.talk(K.UP, "04-dr-mica", 4)
    close(2)
    at(P, 45, 33)
    D.shot("05-crystal-garden")
    at(P, 46, 17)
    D.shot("06-ruby-crystal")
    D.talk(K.UP, "07-touch-ruby", 2)
    D.press(K.A, 60)
    D.wait(120)
    D.shot("08-ruby-lit")
    D.press(K.A, 120)
    D.shot("09-red-pads-wake")
    close(1)
    at(P, 22, 38)
    D.shot("10-red-pad-awake")
    step(K.DOWN, "11-teleporting")
    D.shot("12-west-gallery")
    at(P, 8, 5)
    D.talk(K.UP, "13-touch-sapphire", 2)
    D.press(K.A, 60)
    D.wait(120)
    D.shot("14-sapphire-lit")
    close(2)
    at(P, 11, 6)
    step(K.DOWN)
    D.shot("15-north-hall")
    at(P, 30, 8)
    D.talk(K.UP, "16-carving", 3)
    close(1)
    at(P, 38, 6)
    step(K.UP)
    D.wait(200)
    D.shot("17-depths-landing")
    at(B, 24, 27)
    D.talk(K.UP, "18-seal", 2)
    close(1)
    at(B, 10, 30)
    step(K.DOWN)
    D.shot("19-island-c")
    at(B, 3, 7)
    step(K.DOWN)
    D.shot("20-island-e-emerald")
    at(B, 5, 20)
    D.talk(K.UP, "21-touch-emerald", 2)
    D.press(K.A, 60)
    D.wait(120)
    D.shot("22-emerald-lit")
    close(2)
    at(B, 11, 20)
    step(K.DOWN)
    D.shot("23-island-f-topaz")
    at(B, 43, 20)
    D.talk(K.UP, "24-touch-topaz", 2)
    D.press(K.A, 60)
    D.wait(120)
    D.shot("25-topaz-lit")
    D.press(K.A, 60)
    D.press(K.A, 60)
    D.wait(60)
    D.shot("26-all-four")
    D.press(K.A, 60)
    D.wait(200)
    D.shot("27-seal-breaks")
    close(2)
    at(B, 24, 22)
    D.shot("28-seal-open")
    at(B, 24, 9)
    D.shot("29-heart-chamber")
    D.talk(K.UP, "30-diancie", 2)
    D.press(K.A, 60)
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(300)
    D.shot("31-diancie-battle")
    D.result("ok")
end)
