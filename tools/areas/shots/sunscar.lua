-- Sunscar Desert and Ruins: the guide in Mauville, the desert, the hall of
-- riddles solved in order (sun, moon, wave), the vault and Spiritomb.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local SD = MAPS.MAP_SUNSCAR_DESERT
local HALL = MAPS.MAP_SUNSCAR_RUINS_HALL

local function say(dir, name, pages)
    D.talk(dir, name, pages)
    D.wait(30)
end

-- Reads a glyph tablet (standing below it) and presses YES.
local function touch(x, name)
    D.scene(12, HALL, x, 7)
    D.talk(K.UP, name, 1)
    D.press(K.A, 90)
    D.shot(name .. "-result")
    D.press(K.A, 30)
end

D.run(function()
    D.boot()
    D.wait(60)
    D.flag("FLAG_BADGE06_GET", true)
    D.scene(12, MAPS.MAP_MAUVILLE_CITY, 26, 8)
    D.shot("01-mauville-guide")
    say(K.UP, "02-guide", 2)
    D.press(K.A, 30)
    D.wait(200)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(120)
    D.shot("03-arrive")
    D.scene(12, SD, 24, 30); D.wait(60); D.shot("04-desert")
    D.scene(12, SD, 24, 13); D.wait(60); D.shot("05-ruins-mouth")
    D.scene(12, SD, 26, 12); say(K.RIGHT, "06-archaeologist", 3)
    D.scene(12, HALL, 12, 15); D.wait(60); D.shot("07-hall")
    D.scene(12, HALL, 8, 10); say(K.UP, "08-riddle-1", 2)
    touch(18, "09-moon-too-early")
    touch(5, "10-sun")
    D.scene(12, HALL, 12, 10); say(K.UP, "11-riddle-2", 2)
    touch(18, "12-moon")
    D.scene(12, HALL, 16, 10); say(K.UP, "13-riddle-3", 2)
    D.scene(12, HALL, 5, 13)
    D.talk(K.UP, "14-wave", 1)
    D.press(K.A, 90)
    D.shot("15-statue-glows")
    D.press(K.A, 30)
    D.shot("16-rumble")
    D.press(K.A, 20)
    D.wait(150)
    D.shot("17-door-opens")
    D.press(K.A, 30)
    D.scene(12, HALL, 12, 3); D.wait(60); D.shot("18-open-door")
    D.hold(K.UP, 20)
    D.wait(150)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(60)
    D.shot("19-vault")
    D.scene(12, MAPS.MAP_SUNSCAR_RUINS_VAULT, 10, 6)
    say(K.UP, "20-spiritomb", 1)
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(400)
    D.shot("21-spiritomb-battle")
    D.result("ok")
end)
