-- Solmara tour: the ship from Lilycove, Port Solace, the flight desk, every
-- town, a few routes, the Victory Road gate, the League and a gym leader.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY

local function view(map, x, y, name)
    D.scene(12, MAPS[map], x, y)
    D.wait(240)
    D.press(K.B, 30)
    D.wait(30)
    D.shot(name)
end

local VISITED = { "FLAG_SOL_VISITED_PORT_SOLACE", "FLAG_SOL_VISITED_GEARHOLT", "FLAG_SOL_VISITED_ASHCOMBE", "FLAG_SOL_VISITED_SILKWOOD", "FLAG_SOL_VISITED_ROSEMEAD", "FLAG_SOL_VISITED_DUSKMERE", "FLAG_SOL_VISITED_FROSTHOLM", "FLAG_SOL_VISITED_DRAKESPIRE" }
local BADGES = { "FLAG_SOL_BADGE_1", "FLAG_SOL_BADGE_2", "FLAG_SOL_BADGE_3", "FLAG_SOL_BADGE_4", "FLAG_SOL_BADGE_5", "FLAG_SOL_BADGE_6", "FLAG_SOL_BADGE_7", "FLAG_SOL_BADGE_8" }

D.run(function()
    D.boot()
    D.wait(60)
    D.season(1)
    D.flag("FLAG_SYS_GAME_CLEAR", true)
    D.scene(12, MAPS.MAP_LILYCOVE_CITY_HARBOR, 13, 11, { give = "SWAMPERT", level = 60, lead = true })
    D.wait(300)
    D.press(K.B, 30)
    D.talk(K.RIGHT, "01-lilycove-sailor", 2)
    for _ = 1, 4 do D.press(K.A, 60) end
    D.wait(300)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(200)
    D.shot("02-ship-lounge")
    D.scene(12, MAPS.MAP_SOLMARA_SHIP_LOUNGE, 15, 11)
    D.wait(200)
    D.talk(K.RIGHT, "03-steward", 1)
    D.press(K.B, 30)
    D.press(K.B, 30)
    view("MAP_PORT_SOLACE", 21, 29, "04-port-solace-dock")
    view("MAP_PORT_SOLACE", 12, 24, "05-port-solace-town")
    -- Victory Road turns you back without all eight badges.
    D.scene(12, MAPS.MAP_PORT_SOLACE, 24, 7)
    D.wait(200)
    D.hold(K.UP, 40)
    D.wait(60)
    D.shot("06-victory-road-needs-badges")
    D.press(K.A, 60)
    D.press(K.A, 60)
    D.press(K.B, 60)
    for i = 1, 8 do D.flag(VISITED[i], true) end
    view("MAP_PORT_SOLACE_POKEMON_CENTER_1_F", 7, 6, "07-pokemon-center")
    D.scene(12, MAPS.MAP_PORT_SOLACE_POKEMON_CENTER_1_F, 2, 3)
    D.wait(200)
    D.talk(K.LEFT, "08-flight-desk", 2)
    D.wait(60)
    D.shot("09-flight-menu")
    D.press(K.B, 60)
    D.press(K.B, 60)
    D.press(K.B, 60)
    view("MAP_GEARHOLT", 11, 12, "10-gearholt")
    view("MAP_ASHCOMBE", 12, 17, "11-ashcombe")
    view("MAP_SILKWOOD", 10, 12, "12-silkwood")
    view("MAP_ROSEMEAD", 11, 22, "13-rosemead")
    view("MAP_DUSKMERE", 24, 12, "14-duskmere")
    view("MAP_FROSTHOLM", 13, 17, "15-frostholm")
    view("MAP_DRAKESPIRE", 25, 12, "16-drakespire")
    view("MAP_ROUTE201", 20, 11, "17-route-201")
    view("MAP_ROUTE202", 11, 30, "18-route-202")
    view("MAP_ROUTE204", 30, 11, "19-route-204")
    view("MAP_ROUTE206", 11, 30, "20-route-206")
    view("MAP_ASHCOMBE_GYM", 10, 17, "21-ashcombe-gym")
    view("MAP_DUSKMERE_GYM", 10, 17, "22-duskmere-gym")
    for n = 1, 8 do D.flag(BADGES[n], true) end
    view("MAP_SOLMARA_VICTORY_ROAD", 20, 38, "23-victory-road")
    view("MAP_SOLMARA_LEAGUE", 14, 28, "24-league")
    view("MAP_SOLMARA_LEAGUE_LOBBY", 9, 9, "25-league-lobby")
    view("MAP_SOLMARA_LEAGUE_CHAMPION", 6, 7, "26-champion-room")
    D.scene(12, MAPS.MAP_PORT_SOLACE_GYM, 10, 3)
    D.wait(200)
    D.talk(K.UP, "27-leader-marina", 2)
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(300)
    D.shot("28-marina-battle")
    D.result("ok")
end)
