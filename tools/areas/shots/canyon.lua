-- Skyrope Canyon: the guide in Fallarbor, the mesas and rope bridges, the
-- Bridgewright's quest (a rope coil, the mended bridge) and Hawlucha.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local SC = MAPS.MAP_SKYROPE_CANYON

local function say(dir, name, pages)
    D.talk(dir, name, pages)
    D.wait(30)
end

D.run(function()
    D.boot()
    D.wait(60)
    D.flag("FLAG_BADGE05_GET", true)
    D.scene(12, MAPS.MAP_FALLARBOR_TOWN, 17, 11)
    D.shot("01-fallarbor-guide")
    say(K.RIGHT, "02-guide", 2)
    D.press(K.A, 30)
    D.wait(200)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(120)
    D.shot("03-arrive")
    D.scene(12, SC, 39, 51); D.wait(60); D.shot("04-basin")
    D.scene(12, SC, 15, 7); D.wait(60); D.shot("04b-north-basin")
    D.scene(12, SC, 10, 30); D.shot("05-west-bridge")
    D.scene(12, SC, 33, 27); D.shot("06-centre-bridge")
    D.scene(12, SC, 52, 22); D.shot("07-broken-bridge")
    D.scene(12, SC, 43, 45); say(K.UP, "08-bridgewright", 5)
    D.scene(12, SC, 24, 50); say(K.UP, "09-rope", 1)
    D.press(K.A, 60)
    D.flag("FLAG_SKYROPE_ROPE_1", true)
    D.flag("FLAG_SKYROPE_ROPE_2", true)
    D.flag("FLAG_SKYROPE_ROPE_3", true)
    D.scene(12, SC, 43, 45); say(K.UP, "10-all-ropes", 1)
    D.wait(200)
    D.shot("11-mending")
    D.press(K.A, 30)
    D.shot("12-mended")
    D.press(K.A, 30)
    D.press(K.A, 30)
    D.scene(12, SC, 52, 29); D.shot("13-mended-bridge")
    D.scene(12, SC, 49, 12); D.shot("14-ledge")
    D.scene(12, SC, 49, 7)
    D.talk(K.UP, "15-hawlucha", 1)
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(400)
    D.shot("16-hawlucha-battle")
    D.result("ok")
end)
