-- Hollowmere: the ferryman in Lilycove (day: no; night: yes), the town at
-- night, the caretaker's lost ghosts, the dark manor, and Mimikyu upstairs.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local HM = MAPS.MAP_HOLLOWMERE
local M1 = MAPS.MAP_HOLLOWMERE_MANOR_1F

local function say(dir, name, pages)
    D.talk(dir, name, pages)
    D.wait(30)
end

D.run(function()
    D.boot()
    D.wait(60)
    D.flag("FLAG_BADGE07_GET", true)
    D.scene(12, MAPS.MAP_LILYCOVE_CITY, 27, 17)
    say(K.UP, "01-ferryman-day", 2)
    D.scene(22, MAPS.MAP_LILYCOVE_CITY, 27, 17)
    D.shot("02-lilycove-night")
    say(K.UP, "03-ferryman-night", 1)
    D.press(K.A, 30)
    D.wait(200)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(120)
    D.shot("04-arrive")
    D.scene(22, HM, 22, 20); D.wait(60); D.shot("05-town")
    D.scene(22, HM, 22, 9); D.wait(60); D.shot("06-manor")
    D.scene(22, HM, 20, 11); say(K.UP, "07-caretaker", 5)
    D.scene(22, HM, 5, 20); D.wait(30)
    D.talk(K.LEFT, "08-gastly", 1)
    D.press(K.A, 90)
    D.shot("09-gastly-home")
    D.press(K.A, 30)
    D.scene(22, MAPS.MAP_HOLLOWMERE_INN, 5, 5); say(K.UP, "10-inn", 1)
    D.press(K.B, 60)
    D.scene(22, M1, 9, 12); D.wait(60); D.shot("11-dark-manor")
    D.scene(22, M1, 16, 3); say(K.UP, "12-butler", 2)
    D.flag("FLAG_HOLLOW_GHOST_GASTLY", true)
    D.flag("FLAG_HOLLOW_GHOST_DUSKULL", true)
    D.flag("FLAG_HOLLOW_GHOST_SHUPPET", true)
    D.flag("FLAG_HOLLOW_GHOST_MISDREAVUS", true)
    D.scene(22, HM, 20, 11); say(K.UP, "13-all-home", 1)
    D.wait(60)
    D.press(K.A, 60)
    D.shot("14-key")
    D.press(K.A, 60)
    D.press(K.A, 30)
    D.press(K.A, 30)
    D.scene(22, M1, 16, 3); D.wait(60); D.shot("15-butler-aside")
    D.hold(K.UP, 40)
    D.wait(150)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(60)
    D.shot("16-manor-2f")
    D.scene(22, MAPS.MAP_HOLLOWMERE_MANOR_2F, 10, 9)
    say(K.UP, "17-doll", 1)
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(400)
    D.shot("18-mimikyu-battle")
    D.result("ok")
end)
