-- Ember Springs: the guide in Lavaridge, the town, a soak, the Slugma on
-- the vents, the Spring Keeper, the Old Spring and the egg, a trainer.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY
local ES = MAPS.MAP_EMBER_SPRINGS

local function say(dir, name, pages)
    D.talk(dir, name, pages)
    D.wait(30)
end

D.run(function()
    D.boot()
    D.wait(60)
    D.flag("FLAG_BADGE04_GET", true)
    D.scene(12, MAPS.MAP_LAVARIDGE_TOWN, 17, 10)
    D.shot("01-lavaridge-guide")
    say(K.RIGHT, "02-guide", 2)
    D.wait(200)
    D.waitFor("the overworld", 1200, D.inOverworld)
    D.wait(120)
    D.shot("03-arrive")
    D.scene(12, ES, 22, 20); D.shot("04-town")
    D.scene(12, ES, 16, 13); D.shot("05-pokecenter-inn")
    D.scene(12, ES, 16, 20); say(K.LEFT, "06-soak", 3)
    D.wait(120); D.shot("07-soaked")
    D.press(K.A, 40)
    D.scene(12, ES, 21, 16); say(K.UP, "08-keeper", 4)
    D.scene(12, ES, 6, 7); say(K.UP, "09-slugma", 1)
    D.waitFor("the battle", 1500, D.inBattle)
    D.wait(350)
    D.shot("10-slugma-battle")
    D.runAway()
    D.wait(200)
    D.shot("11-vent-cleared")
    D.flag("FLAG_EMBER_SLUGMA_WEST", true)
    D.flag("FLAG_EMBER_SLUGMA_NORTH", true)
    D.flag("FLAG_EMBER_SLUGMA_EAST", true)
    D.flag("FLAG_EMBER_QUEST_DONE", true)
    D.scene(12, ES, 34, 26); D.shot("12-old-spring-open")
    D.scene(12, ES, 35, 32); say(K.DOWN, "13-egg", 5)
    D.scene(12, MAPS.MAP_EMBER_SPRINGS_INN, 4, 4); say(K.UP, "14-inn", 1)
    D.press(K.B, 60)
    D.scene(12, MAPS.MAP_EMBER_SPRINGS_POKEMON_CENTER_1F, 7, 4); D.shot("15-pokecenter")
    D.scene(12, ES, 24, 24)
    D.wait(200)
    D.shot("16-saki-spots")
    D.press(K.A, 120)
    D.waitFor("the battle", 1500, D.inBattle, function(i) if i % 40 == 0 then D.press(K.A, 0) end end)
    D.wait(300)
    D.shot("17-saki-battle")
    D.result("ok")
end)
