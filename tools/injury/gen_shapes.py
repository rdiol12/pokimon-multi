#!/usr/bin/env python3
"""Generate src/data/injury_shapes.h: the Pokedex body shape of every species,
indexed by national dex number. The game uses it to decide which body parts a
species can injure or lose (see src/injury.c).

Source: PokeAPI's pokemon_species.csv (column shape_id), e.g.
https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species.csv
Usage: gen_shapes.py pokemon_species.csv > src/data/injury_shapes.h
"""
import csv, sys

NAMES = {1: 'BALL', 2: 'SQUIGGLE', 3: 'FISH', 4: 'ARMS', 5: 'BLOB', 6: 'UPRIGHT',
         7: 'LEGS', 8: 'QUADRUPED', 9: 'WINGS', 10: 'TENTACLES', 11: 'HEADS',
         12: 'HUMANOID', 13: 'BUG_WINGS', 14: 'ARMOR'}

rows = {}
with open(sys.argv[1], newline='') as f:
    for r in csv.DictReader(f):
        n = int(r['id'])
        if n <= 1025 and r['shape_id']:
            rows[n] = int(r['shape_id'])

print('// Generated by tools/injury/gen_shapes.py from PokeAPI data. Do not edit.')
print('// Pokedex body shape per national dex number (BODY_SHAPE_*).')
print('static const u8 sInjuryBodyShapes[] =')
print('{')
for n in sorted(rows):
    print(f'    [{n}] = BODY_SHAPE_{NAMES[rows[n]]},')
print('};')
