import sys
def conv(rows):  # rows: list of 16 strings of 16 chars '.', '1','2','3'
    out=[]
    for ty in range(2):
        for tx in range(2):
            for y in range(8):
                v=0
                for x in range(8):
                    c=rows[ty*8+y][tx*8+x]
                    n=0 if c=='.' else int(c,16)
                    v|=n<<(4*x)
                out.append(v)
    return out
