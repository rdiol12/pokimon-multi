#!/usr/bin/env python3
"""Writes the trainer-level outfits (docs/adventure.md): one recoloured
palette per outfit and gender, and the object event graphics that draw
Brendan and May with them.

Outfits only recolour the clothes, so every graphic reuses Brendan's or
May's own pictures and animations; only the palette tag differs. The
colours are picked from existing Emerald palettes and keep each original
ramp's light-to-dark steps.

Run from the repository root:  python3 tools/adventure/gen_outfits.py
"""
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PAL_DIR = os.path.join(ROOT, "graphics", "object_events", "palettes")
INFO_H = os.path.join(ROOT, "src", "data", "object_events", "object_event_graphics_info.h")
OUT_H = os.path.join(ROOT, "src", "data", "object_events", "outfit_graphics_info.h")
OUT_PTRS = os.path.join(ROOT, "src", "data", "object_events", "outfit_graphics_info_pointers.h")

# Which palette indices are which part of the outfit.
#   Brendan: 5-8 clothes (dark to darkest), 10-11 bandana, 12-13 trim
#   May:     5-6 shorts, 10-11 bandana, 12-13 top
PARTS = {
    "brendan": {"clothes": [5, 6, 7, 8], "bandana": [10, 11], "trim": [12, 13]},
    "may": {"clothes": [5, 6], "bandana": [10, 11], "trim": [12, 13]},
}

# name, {part: [colours, light to dark]}
OUTFITS = [
    ("Autumn", {
        "clothes": [(123, 82, 57), (98, 65, 41), (74, 49, 32), (49, 32, 24)],
        "bandana": [(255, 164, 57), (205, 106, 32)],
        "trim": [(255, 213, 74), (205, 156, 32)],
    }),
    ("Starlight", {
        "clothes": [(65, 57, 123), (49, 41, 98), (32, 32, 82), (24, 16, 57)],
        "bandana": [(180, 139, 238), (123, 90, 189)],
        "trim": [(148, 222, 255), (82, 156, 213)],
    }),
    ("Ace", {
        "clothes": [(213, 213, 222), (164, 164, 180), (115, 115, 131), (74, 74, 90)],
        "bandana": [(98, 156, 238), (57, 98, 189)],
        "trim": [(65, 123, 230), (32, 74, 164)],
    }),
    ("Shadow", {
        "clothes": [(65, 65, 74), (49, 49, 57), (32, 32, 41), (16, 16, 24)],
        "bandana": [(230, 74, 74), (164, 32, 41)],
        "trim": [(172, 82, 197), (115, 49, 139)],
    }),
    ("Champion", {
        "clothes": [(238, 238, 246), (197, 197, 213), (148, 148, 164), (98, 98, 115)],
        "bandana": [(255, 222, 82), (222, 164, 32)],
        "trim": [(255, 213, 74), (197, 139, 24)],
    }),
]

# Avatar states that get an outfit (underwater has its own palette).
STATES = ["Normal", "MachBike", "AcroBike", "Surfing", "FieldMove", "Fishing", "Watering"]
GENDERS = [("Brendan", "brendan", "BRENDAN"), ("May", "may", "MAY")]


def read_pal(path):
    with open(path) as f:
        lines = f.read().split("\n")
    return [tuple(int(v) for v in line.split()) for line in lines[3:19]]


def write_pal(path, colours):
    with open(path, "w", newline="\n") as f:
        f.write("JASC-PAL\n0100\n16\n")
        for c in colours:
            f.write("%d %d %d\n" % c)


def info_block(text, name):
    m = re.search(r"const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_%s = \{\n(.*?)\n\};" % name, text, re.S)
    return m.group(1)


def main():
    with open(INFO_H) as f:
        infos = f.read()
    out = ["// Generated by tools/adventure/gen_outfits.py; do not edit.", ""]
    externs = ["// Generated by tools/adventure/gen_outfits.py; do not edit.",
               "// Graphics id OBJ_EVENT_GFX_OUTFIT_FIRST + ((outfit - 1) * 2 + gender) * OUTFIT_STATES + state.", ""]
    pointers = ["#define OUTFIT_GRAPHICS_INFO_POINTERS \\"]
    gfx = 0
    for i, (outfit, colours) in enumerate(OUTFITS):
        for gname, gfile, gtag in GENDERS:
            pal = read_pal(os.path.join(PAL_DIR, gfile + ".pal"))
            for part, idx in PARTS[gfile].items():
                for n, j in enumerate(idx):
                    pal[j] = colours[part][min(n, len(colours[part]) - 1)]
            palname = "outfit_%s_%s" % (outfit.lower(), gfile)
            write_pal(os.path.join(PAL_DIR, palname + ".pal"), pal)
            sym = "gObjectEventPal_Outfit%s%s" % (outfit, gname)
            out.append('const u16 %s[] = INCGFX_U16("graphics/object_events/palettes/%s.pal", ".gbapal");' % (sym, palname))
            tag = "OBJ_EVENT_PAL_TAG_OUTFIT_%s_%s" % (outfit.upper(), gtag)
            for state in STATES:
                body = info_block(infos, gname + state)
                body = re.sub(r"\.paletteTag = \w+", ".paletteTag = " + tag, body)
                name = "gObjectEventGraphicsInfo_Outfit%s%s%s" % (outfit, gname, state)
                externs.append("extern const struct ObjectEventGraphicsInfo %s;" % name)
                pointers.append("    [OBJ_EVENT_GFX_OUTFIT_FIRST + %d] = &%s, \\" % (gfx, name))
                gfx += 1
                out.append("const struct ObjectEventGraphicsInfo %s = {" % name)
                out.append(body)
                out.append("};")
            out.append("")
    with open(OUT_H, "w") as f:
        f.write("\n".join(out))
    pointers.append("")
    with open(OUT_PTRS, "w") as f:
        f.write("\n".join(externs + [""] + pointers) + "\n")
    print("wrote", OUT_H, "and", OUT_PTRS, "-", gfx, "graphics")


if __name__ == "__main__":
    main()
