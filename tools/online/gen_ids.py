#!/usr/bin/env python3
"""Writes server/online_ids.py: item, species and map numbers from the game's
headers, so the server (which ships without the game's source) can name
rewards and read reports. Run it after adding items, species or maps."""
import json
import os
import re

root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def enum(path, prefix):
    text = open(os.path.join(root, path)).read()
    return {m.group(1): int(m.group(2)) for m in re.finditer(rf"^\s+{prefix}(\w+) = (\d+),", text, re.M)}


def maps():
    text = open(os.path.join(root, "include", "constants", "map_groups.h")).read()
    return {n: [int(g), int(num)] for n, num, g in
            re.findall(r"^\s+MAP_(\w+)\s+= \((\d+) \| \((\d+) << 8\)\),", text, re.M)}


def map_sections():
    """MAP name -> region map section, and section -> [x, y, w, h] on the
    region map grid, for the website's live map."""
    sections = {}
    for d in sorted(os.listdir(os.path.join(root, "data", "maps"))):
        path = os.path.join(root, "data", "maps", d, "map.json")
        if os.path.exists(path):
            m = json.load(open(path))
            if "id" in m and "region_map_section" in m:
                sections[m["id"][4:]] = m["region_map_section"]
    grid = {}
    data = json.load(open(os.path.join(root, "src", "data", "region_map", "region_map_sections.json")))
    for s in data["map_sections"]:
        if "x" in s:
            grid[s["id"]] = [s["x"], s["y"], s.get("width", 1), s.get("height", 1), s.get("name", "")]
    return sections, grid


def main():
    items = enum("include/constants/items.h", "ITEM_")
    species = enum("include/constants/species.h", "SPECIES_")
    sections, grid = map_sections()
    out = ['"""Generated by tools/online/gen_ids.py from the game\'s headers. Do not edit."""', ""]
    out.append("ITEMS = " + json.dumps(items, sort_keys=True))
    out.append("SPECIES = " + json.dumps(species, sort_keys=True))
    out.append("MAPS = " + json.dumps(maps(), sort_keys=True))
    out.append("MAP_SECTIONS = " + json.dumps(sections, sort_keys=True))
    out.append("SECTION_GRID = " + json.dumps(grid, sort_keys=True))
    out.append("SPECIES_NAMES = {v: k for k, v in SPECIES.items()}")
    out.append("MAP_NAMES = {tuple(v): k for k, v in MAPS.items()}")
    open(os.path.join(root, "server", "online_ids.py"), "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
