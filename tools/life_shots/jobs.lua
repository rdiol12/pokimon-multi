-- Pokémon jobs: send Geodude on a cave survey from the Mauville Pokémon
-- Center, check R > JOBS, then pick it up when the time is done.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY

D.run(function()
    D.boot()
    D.wait(60)
    D.scene(14, MAPS.MAP_MAUVILLE_CITY_POKEMON_CENTER_1F, 5, 4, { give = "GEODUDE", level = 20, lead = true })
    D.shot("agent")
    D.hold(K.LEFT, 2)
    D.wait(10)
    D.press(K.A, 90)
    D.shot("agent-menu")
    D.press(K.A, 60)
    D.shot("job-list")
    for _ = 1, 4 do D.press(K.DOWN, 8) end
    D.wait(10)
    D.shot("job-cave-survey")
    D.press(K.A, 60)
    D.shot("job-about")
    D.press(K.A, 40)
    D.press(K.A, 40)
    D.wait(30)
    D.shot("job-about-2")
    D.press(K.A, 120) -- YES
    D.shot("job-party")
    D.press(K.A, 90) -- Geodude
    D.shot("job-sent")
    D.press(K.B, 50)
    D.shot("job-sent-2")
    for _ = 1, 4 do D.press(K.B, 30) end
    D.press(K.R, 60)
    D.press(K.DOWN, 20)
    D.press(K.DOWN, 20)
    D.press(K.A, 60)
    D.shot("jobs-board")
    D.press(K.B, 30)
    -- Four hours later.
    D.write8(D.SYM.gLifeShowcase + 3, 1)
    D.write8(D.SYM.gLifeShowcase, 1)
    D.wait(10)
    D.hold(K.LEFT, 2)
    D.wait(10)
    D.press(K.A, 120)
    D.shot("job-back")
    D.press(K.A, 40)
    D.wait(20)
    D.shot("job-back-2")
    D.press(K.A, 200)
    D.shot("job-back-3")
    D.press(K.A, 60)
    D.shot("job-back-4")
    D.press(K.A, 60)
    D.shot("job-back-5")
end)
