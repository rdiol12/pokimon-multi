-- Cave bosses: the Terastal Sableye in Granite Cave and the Dynamax
-- Lunatone in Meteor Falls.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY

D.run(function()
    D.boot()
    D.wait(60)
    D.scene(13, MAPS.MAP_GRANITE_CAVE_1F, 33, 5, { give = "AGGRON", level = 40, lead = true })
    D.fastText()
    D.mech({ fixMoves = true, badges = 8, moves = { "METAL_CLAW", "ROCK_SLIDE", "EARTHQUAKE", "PROTECT" } })
    D.wait(20)
    D.hold(K.LEFT, 16)
    D.wait(30)
    D.shot("granite")
    D.step(K.A, "granite-intro", 120)
    D.step(K.A, "granite-intro")
    D.step(K.A, "granite-start", 200)
    D.fight("granite-battle", 50, 24)
    D.step(K.A, "granite-after")
    D.step(K.A, "granite-after")
    D.step(K.A, "granite-after")
    D.scene(13, MAPS.MAP_METEOR_FALLS_1F_2R, 11, 28, { give = "SCEPTILE", level = 50, lead = true })
    D.mech({ fixMoves = true, moves = { "BULLET_SEED", "EARTHQUAKE", "DRAGON_CLAW", "PROTECT" } })
    D.wait(20)
    D.hold(K.RIGHT, 16)
    D.wait(30)
    D.shot("meteor")
    D.step(K.A, "meteor-intro", 120)
    D.step(K.A, "meteor-intro")
    D.step(K.A, "meteor-start", 200)
    D.fight("meteor-battle", 50, 30)
    D.step(K.A, "meteor-after")
    D.step(K.A, "meteor-after")
    D.step(K.A, "meteor-after")
    D.result("ok")
end)
