-- The move tutor in a Pokémon Center: first meeting, the menu, and the
-- Egg Moves a Treecko can learn.
dofile(INSTANCE_DIR .. "/../driver_lib.lua")
local D, K = Driver, Driver.KEY

D.run(function()
    D.boot()
    D.wait(60)
    D.scene(13, MAPS.MAP_OLDALE_TOWN_POKEMON_CENTER_1F, 12, 5, { give = "TREECKO", level = 20, lead = true })
    D.fastText()
    D.shot("center")
    D.hold(K.RIGHT, 2)
    D.wait(10)
    for i = 1, 6 do D.step(K.A, "talk") end
    D.step(K.A, "menu")
    D.step(K.DOWN, "menu-egg")
    D.step(K.A, "choose")
    D.step(K.A, "box")
    D.step(K.UP, "u1")
    D.step(K.UP, "u2")
    D.step(K.A, "a1")
    D.step(K.A, "a2")
    D.step(K.A, "a3")
    D.step(K.A, "a4")
    D.step(K.A, "list", 150)
    D.step(K.DOWN, "list-2")
    D.step(K.DOWN, "list-3")
    D.step(K.B, "q1")
    D.step(K.A, "q2", 150)
    for _ = 1, 4 do D.step(K.B, "q3") end
    D.scene(13, MAPS.MAP_LAVARIDGE_TOWN_POKEMON_CENTER_1F, 10, 5)
    D.shot("lavaridge")
    D.scene(13, MAPS.MAP_MOSSDEEP_CITY_POKEMON_CENTER_1F, 12, 5)
    D.shot("mossdeep")
    D.hold(K.RIGHT, 2)
    D.wait(10)
    D.step(K.A, "mossdeep-again")
    D.result("ok")
end)
